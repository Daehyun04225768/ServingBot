# 1. 교수님이 만든 로봇 엔진을 불러옵니다. (수정 금지)
from serving_robot import ServingRobot
import time

# 2. 로봇의 전원을 켜고 연결합니다. (Unity 시뮬레이터가 켜져 있어야 합니다)
robot = ServingRobot()
print("\n=== 🚀 로봇 조종 실습을 시작합니다! ===\n")

try:
    # ----------------------------------------------------------
    # 👇 여기서부터 자유롭게 명령을 내려보세요!
    # ----------------------------------------------------------
    
    
    count = 0  # 현재 그린 변의 개수를 저장하는 변수

    # [1회차]
    if count == 0:
        robot.move(10)
        robot.turn(90)
        count = 1  # 완료 후 카운트 증가

    # [2회차]
    if count == 1:
        robot.move(12)
        robot.turn(90)
        count = 2

    # [3회차]
    if count == 2:
        robot.move(10)
        robot.turn(90)
        count = 3

    # [4회차]
    if count == 3:
        robot.move(12)
        print("사각형 완성!")
        robot.led_on() # 완성 기념 불빛!
        count = 4
    
    # ----------------------------------------------------------

except Exception as e:
    print(f"\n[오류 발생] 로봇 조종 중 문제가 발생했습니다: {e}")

finally:
    # 3. 실습이 끝나면 안전하게 로봇과의 연결을 종료합니다.
    robot.close()
    print("\n=== 🏁 실습이 종료되었습니다. ===")